function moveCard(btn, dir) {
  const card = btn.closest('.entity-card, .location-card');
  if(!card) return;
  const parent = card.parentElement;
  if(dir === -1) { const prev = card.previousElementSibling; if(prev) parent.insertBefore(card, prev); }
  else { const next = card.nextElementSibling; if(next) parent.insertBefore(next, card); }
  autosave();
}

