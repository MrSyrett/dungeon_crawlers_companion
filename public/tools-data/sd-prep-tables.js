// in the page, so declaration order and scoping are unchanged.
// RANDOM GENERATORS
// Rulebook dice tables are stored as [[weight, result], ...] (weight = how many
// faces of the die give that result, e.g. "50-53" = 4 on a d100) and expanded so a
// uniform pick reproduces the book's odds exactly.
