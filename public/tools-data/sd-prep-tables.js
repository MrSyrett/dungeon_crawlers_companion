function randTitle() {
  const style = Math.floor(Math.random()*4);
  let t;
  if(style === 0) {
    // ToAD 1-1A: Description + Structure Type + Feature1 + Feature2
    t = _R(TOAD_STRUCT_DESC) + ' ' + _R(TOAD_STRUCT_TYPE) + ' ' + _R(TOAD_FEAT_1) + _R(TOAD_FEAT_2);
  } else if(style === 1) {
    // ToAD: Structure Type + Feature1 + Feature2
    t = 'The ' + _R(TOAD_STRUCT_TYPE) + ' ' + _R(TOAD_FEAT_1) + _R(TOAD_FEAT_2);
  } else if(style === 2) {
    // Classic adjective + noun
    t = 'The ' + _R(TOAD_STRUCT_DESC) + ' ' + _R(TOAD_STRUCT_TYPE).replace(' of the','');
  } else {
    // Noun of the X
    t = 'The ' + _R(TOAD_STRUCT_TYPE) + _R(ADV_TITLE_OF).replace('the ','the ');
  }
  const el = document.getElementById('f-title');
  if(el){ el.value = t; autosave(); }
}

// ── Overview: cohesive mission from ToAD tables ───────────────────────────
function randOverview() {
  const el = document.getElementById('f-overview');
  if(!el) return;
  const type = _R(TOAD_MISSION_TYPES);
  let mission;
  if(type === 'Individual') {
    mission = _R(TOAD_MISSIONS_IND) + ' ' + _R(TOAD_TARGETS_IND);
  } else if(type === 'Item') {
    mission = _R(TOAD_MISSIONS_ITEM) + ' ' + _R(TOAD_ITEMS);
  } else if(type === 'Location') {
    mission = _R(TOAD_MISSIONS_LOC) + ' ' + _R(TOAD_LOC_SUBJECTS);
  } else {
    mission = _R(TOAD_MISSIONS_EVT) + ' ' + _R(TOAD_EVT_SUBJECTS);
  }
  el.value = mission.charAt(0).toUpperCase() + mission.slice(1) + '.';
  autosave();
}

// ── Secrets & Clues ───────────────────────────────────────────────────────
function randSecret() {
  const roll = Math.random();
  if(roll < 0.33) return { type: 'Rumour', text: _R(RUMORS) };
  if(roll < 0.66) return { type: 'Event', text: _R(HAPPENS) };
  return { type: 'Secret', text: _R(SECRETS_D1) + ' ' + _R(SECRETS_D2) };
}
function randClue() {
  const s = randSecret();
  addClue({ header: s.type, text: s.text });
  autosave();
}

