// Generates every Adventure Prep builder from ONE template plus a small config per
// system:
//
//   tools/templates/_prep_template.html      the shared, system-neutral builder
//   scripts/prep-systems/<sys>/meta.json     labels, storage keys, title, system code
//   scripts/prep-systems/<sys>/root-vars.css palette, fonts and masthead (the :root block)
//   scripts/prep-systems/<sys>/extra.css     any extra system CSS (optional)
//   scripts/prep-systems/<sys>/data.html     <script> tags for the system's bestiary/data
//   scripts/prep-systems/<sys>/sb-config.js  stat-card schema + bestiary adapter (SB_CONFIG)
//   scripts/prep-systems/<sys>/title.css     the masthead title rule (fonts per system)
//   scripts/prep-systems/<sys>/homebrew.js   homebrew monsters in the picker (optional)
//   scripts/prep-systems/<sys>/skin.css      a system's own look, loaded after the template CSS (optional)
//   scripts/prep-systems/<sys>/ext.js        system plug-in code (optional)
//   scripts/prep-systems/<sys>/ext.html      system plug-in markup slots (optional, JSON map)
//
// Edit the template or a system's config, then re-run:
//   node scripts/make-session-builders.mjs [sys ...]
//
// The tab layout and flavour labels live in public/tools-data/prep-registry.js, which
// both the builders and the GM Screen's Adventure Hub read, so they always agree.
//
// Every builder is generated. Dragonbane (db), The Lord of the Rings 5e (lotr) and
// Pirate Borg (pb) were hand-built until 28 Oct 2026; they now run on the template
// with plug-ins (Quest / Job → Adventure Details, journeys and voyages → the Travel
// module, the Adventure Site → Sites, traps → Hazards; LotR's Phase and PB's Ships
// are plug-in tabs). HAND_BUILT is kept for any future builder that needs it.
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TPL = readFileSync(join(ROOT, "tools", "templates", "_prep_template.html"), "utf8");
const CFG_DIR = join(ROOT, "scripts", "prep-systems");
const HAND_BUILT = new Set([]);

const only = process.argv.slice(2);
const read = (d, f, dflt = "") => (existsSync(join(d, f)) ? readFileSync(join(d, f), "utf8") : dflt);

let wrote = 0;
for (const sys of readdirSync(CFG_DIR).sort()) {
  if (HAND_BUILT.has(sys)) continue;
  if (only.length && !only.includes(sys)) continue;
  const d = join(CFG_DIR, sys);
  const meta = JSON.parse(read(d, "meta.json"));
  const slots = JSON.parse(read(d, "ext.html", "{}"));
  const vals = {
    TITLE: meta.title,
    ROOT_VARS: read(d, "root-vars.css").replace(/\n$/, ""),
    CSS_EXTRA: read(d, "extra.css"),
    PICKER_COMMENT: meta.pickerComment,
    DATA_SCRIPTS: read(d, "data.html").replace(/\n$/, ""),
    SB_CONFIG: read(d, "sb-config.js").replace(/\n$/, ""),
    EXT_JS: read(d, "ext.js").replace(/\n$/, ""),
    TITLE_CSS: read(d, "title.css").replace(/\n$/, ""),
    HOMEBREW_JS: read(d, "homebrew.js", "let _hbMobs = [];").replace(/\n$/, ""),
    SESSION_LABEL: meta.sessionLabel || "Session",
    SKIN_CSS: read(d, "skin.css").replace(/\n$/, ""),
    SESSION_KEY: meta.sessionKey,
    LS_KEY: meta.lsKey,
    SYS: meta.cfg,
    SYS_CODE: meta.code,
    SYS_NAME: meta.name,
    CHAPTER_LABEL: meta.chapterLabel,
    CHAPTER_PH: meta.chapterPh,
    CHAPTER_UPPER: meta.chapterUpper,
    TITLE_PH: meta.titlePh,
    SUBTITLE_PH: meta.subtitlePh,
    CAST_TAB: meta.castTab,
    CAST_HEADING: meta.castHeading,
    MOB_LABEL: meta.mobLabel,
    BOSS_LABEL: meta.bossLabel,
    RANDOM_LABEL: meta.randomLabel,
  };
  let s = TPL;
  // Markup slots a system plug-in fills (e.g. SD's generator buttons). Unused slots vanish.
  s = s.replace(/<!--\s*SLOT:([a-z0-9_-]+)\s*-->/gi, (_, k) => slots[k] || "");
  s = s.replace(/\{\{([A-Z_]+)\}\}/g, (all, k) => {
    if (!(k in vals)) throw new Error(`${sys}: unknown placeholder ${all}`);
    return vals[k];
  });
  s = s.replace("<head>", "<head>\n<!-- GENERATED by scripts/make-session-builders.mjs from _prep_template.html + scripts/prep-systems/" + sys + "/ — edit those, then re-run. -->");
  writeFileSync(join(ROOT, "tools", "templates", meta.file), s, "utf8");
  wrote++;
  console.log("wrote", meta.file, (s.length / 1024).toFixed(0) + " KB");
}
if (!wrote) console.log("nothing written" + (only.length ? " for " + only.join(", ") : ""));
